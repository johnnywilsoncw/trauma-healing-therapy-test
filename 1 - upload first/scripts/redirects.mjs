// Permanent redirects for the WordPress → Astro migration.
// Edit this list, then run `npm run redirects` to regenerate vercel.json and docs/redirect-map.md.
// Every destination is a final URL on the new site (no chains).
import { readFileSync, writeFileSync } from 'node:fs';

const service = (cat) => `/${cat === 'teen-therapy' ? 'teen-counseling' : cat}/`;

// Blog posts that were NOT carried over (the client asked to keep the most recent post
// per specialty/modality). Each redirects to the service page for its original category.
const retiredPosts = JSON.parse(readFileSync(new URL('./retired-posts.json', import.meta.url), 'utf8'));

const rules = [
  ...retiredPosts.map((p) => ({ from: `/${p.slug}/`, to: service(p.category), why: `Retired post (${p.category})` })),
  { from: '/therapy-services/', to: '/', why: 'Already redirected on the live site' },
  { from: '/contact-me/', to: '/contact-us/', why: 'Old link on Rates & Fees; already redirected on the live site' },
  { from: '/free-consultation-request/', to: '/contact-us/', why: 'Old link on Rates & Fees; already redirected on the live site' },
  { from: '/sitemap_index.xml', to: '/sitemap.xml', why: 'Yoast sitemap index' },
  { from: '/page-sitemap.xml', to: '/sitemap.xml', why: 'Yoast sitemap' },
  { from: '/post-sitemap.xml', to: '/sitemap.xml', why: 'Yoast sitemap' },
  { from: '/feed/', to: '/blog/', why: 'WordPress feed' },
];

const categoryArchives = ['trauma-therapy', 'emdr-therapy', 'emdr-intensives', 'couples-therapy', 'terapia-in-italiano', 'premarital-counseling', 'lgbtq-therapy', 'therapy-for-women', 'teen-therapy', 'adhd-therapy', 'adhd-testing', 'anxiety-therapy'];
rules.push(...categoryArchives.map((c) => ({ from: `/category/${c}/`, to: service(c), why: 'WordPress category archive' })));

const redirects = [];
for (const r of rules) {
  redirects.push({ source: r.from, destination: r.to, permanent: true });
  if (r.from.endsWith('/')) redirects.push({ source: r.from.slice(0, -1), destination: r.to, permanent: true });
}
redirects.push(
  { source: '/author/:name*', destination: '/our-team/', permanent: true },
  { source: '/category/:name*', destination: '/blog/', permanent: true },
  { source: '/tag/:name*', destination: '/blog/', permanent: true },
);

const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  framework: 'astro',
  buildCommand: 'npm run build',
  outputDirectory: 'dist',
  trailingSlash: true,
  redirects,
  headers: [
    {
      source: '/(.*)',
      headers: [
        { key: 'X-Content-Type-Options', value: 'nosniff' },
        { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
        { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()' },
        { key: 'X-Frame-Options', value: 'SAMEORIGIN' },
      ],
    },
    { source: '/_astro/(.*)', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] },
  ],
};
writeFileSync(new URL('../vercel.json', import.meta.url), JSON.stringify(vercel, null, 2) + '\n');

const md = [
  '# Redirect map',
  '',
  'Generated by `npm run redirects` from `scripts/redirects.mjs`. All are permanent (308) redirects served by Vercel.',
  'Each path also redirects without its trailing slash. Unlisted `/author/*`, `/category/*` and `/tag/*` URLs go to `/our-team/` or `/blog/`.',
  '',
  '| Old URL | New URL | Reason |',
  '|---|---|---|',
  ...rules.map((r) => `| \`${r.from}\` | \`${r.to}\` | ${r.why} |`),
  '',
  '## URLs intentionally not redirected',
  '',
  '| Old URL | Status on new site | Reason |',
  '|---|---|---|',
  '| `/group-therapy/` | 404 | Live page is unfinished Lorem ipsum placeholder text. Needs a decision: supply real copy, or redirect. |',
  '| `/release-of-information/` | 404 | Password-protected on WordPress; content could not be retrieved. Needs a replacement (e.g. a Jane App form) before launch. |',
  '| `/intake-form-for-individuals/` | 404 | Password-protected on WordPress; not linked in navigation. |',
  '| `/intake-form-for-couples/` | 404 | Password-protected on WordPress; not linked in navigation. |',
  '| `/wp-content/uploads/*` | 404 | Images now ship with the site from `src/assets/wp/`. External hotlinks to old image URLs will break. |',
  '',
];
writeFileSync(new URL('../docs/redirect-map.md', import.meta.url), md.join('\n'));
console.log(`vercel.json: ${redirects.length} redirect entries`);
